"use strict";
/* Selah — classic commentary in the verse sheet ("Commentary" tab).
   Two public-domain works, one file per book, fetched when first needed:
     data/comm/jfb/NN.json  Jamieson, Fausset & Brown (1871) — short notes on words and phrases
     data/comm/mh/NN.json   Matthew Henry (1706–1721) — longer devotional exposition by section
   File shape: {intro: html, ch: {"3": [[startVerse, endVerse, html], ...]}}. Row [0,0] is the chapter's
   introduction (JFB also writes its verse-1 notes there). The html is generated by tools/build_commentary.py.
   Settings → Commentary turns the tab on or off and picks the work. */

const COMM_SOURCES={
  jfb:{name:"Jamieson-Fausset-Brown", short:"JFB", credit:"Jamieson, Fausset & Brown, <i>Commentary Critical and Explanatory on the Whole Bible</i> (1871). Public domain."},
  mh:{name:"Matthew Henry", short:"Matthew Henry", credit:"Matthew Henry, <i>Commentary on the Whole Bible</i> (1706–1721). Public domain.", missing:["Song of Solomon"]}
};
const COMM={};   // COMM["jfb|43"] = data or Promise
const commOn=()=>store.get("commOn",true);
const commSrc=()=>{ const s=store.get("commSrc","jfb"); return COMM_SOURCES[s]?s:"jfb"; };
function commFile(src,book){ const n=BOOKS.findIndex(b=>b.name===book)+1; return `data/comm/${src}/${String(n).padStart(2,"0")}.json`; }
function loadComm(src,book){
  const k=src+"|"+book;
  if(!COMM[k]) COMM[k]=getJSON(commFile(src,book)).then(d=>COMM[k]=d).catch(e=>{ delete COMM[k]; throw e; });
  return Promise.resolve(COMM[k]);
}
// Show or hide the sheet tab to match the setting.
function syncCommTab(){
  const b=document.querySelector('#sheetTabs [data-tab="comment"]'); if(!b) return;
  b.hidden=!commOn();
  if(!commOn()&&state.sheetTab==="comment"){ state.sheetTab="xrefs"; if(state.sheetRef) paintSheet(); }
}
function setCommOn(on){ store.set("commOn",!!on); syncCommTab(); }
function setCommSrc(s){ store.set("commSrc",s); if(state.sheetRef&&state.sheetTab==="comment") paintSheet(); }

const vlabel=(s,e)=>e>s?`Verses ${s}–${e}`:`Verse ${s}`;
function commBlock(label,html,cls=""){
  const long=html.length>4500;
  return `<div class="comm-sec${cls}"><div class="comm-lbl">${esc(label)}</div><div class="comm-text${long?" clamp":""}">${html}</div>${long?'<button class="link-btn comm-more">Read the whole section</button>':""}</div>`;
}
async function paintComment(body,ref){
  const p=parseRef(ref); if(!p){ body.innerHTML='<div class="empty">—</div>'; return; }
  const src=commSrc(), S=COMM_SOURCES[src];
  const picker=`<div class="scope-toggle comm-pick">${Object.entries(COMM_SOURCES).map(([k,s])=>`<button data-c="${k}" class="${k===src?"active":""}">${esc(s.short)}</button>`).join("")}</div>`;
  const bindPick=()=>body.querySelectorAll(".comm-pick button").forEach(b=>b.onclick=()=>setCommSrc(b.dataset.c));
  if(S.missing&&S.missing.includes(p.book)){
    body.innerHTML=picker+`<div class="empty">${esc(S.name)}’s commentary in this edition has no notes on ${esc(p.book)}. Jamieson-Fausset-Brown covers it.</div>`;
    bindPick(); return;
  }
  const k=src+"|"+p.book;
  let d=COMM[k];
  if(!d||d instanceof Promise){
    body.innerHTML=picker+'<div class="empty">Loading commentary…</div>'; bindPick();
    try{ d=await loadComm(src,p.book); }
    catch(e){ if(state.sheetRef===ref&&state.sheetTab==="comment"){ body.innerHTML=picker+'<div class="empty">Couldn’t load the commentary. Check your connection and try again.</div>'; bindPick(); } return; }
    if(state.sheetRef!==ref||state.sheetTab!=="comment"||commSrc()!==src) return;
  }
  const rows=(d.ch&&d.ch[p.ch])||[], v=p.v;
  const intro=rows.filter(r=>r[0]===0), notes=rows.filter(r=>r[0]>0);
  let main=notes.filter(r=>r[0]<=v&&v<=r[1]), parts=[], introShown=false;
  if(src==="jfb"&&(v===1||!main.length)&&intro.length){
    // JFB writes its notes on verse 1 into the chapter introduction.
    parts.push(commBlock(v===1?"Chapter "+p.ch+" · verse 1":"Chapter "+p.ch,intro.map(r=>r[2]).join("")));
    introShown=true;
  }
  if(!main.length&&!introShown){
    const prev=notes.filter(r=>r[0]<v).pop();
    if(prev){ main=[prev]; parts.push(`<div class="section-sub comm-near">No note on verse ${v} — the nearest one before it:</div>`); }
  }
  parts.push(...main.map(r=>commBlock(vlabel(r[0],r[1]),r[2],r[0]<v?" near":"")));
  if(!parts.length) parts.push(`<div class="empty">${esc(S.name)} has no note on ${esc(p.book)} ${p.ch}:${v}.</div>`);
  const more=[];
  if(intro.length&&!introShown) more.push(`<details class="comm-more-sec"><summary>About ${esc(p.book)} ${p.ch}</summary><div class="comm-text">${intro.map(r=>r[2]).join("")}</div></details>`);
  if(notes.length>1) more.push(`<details class="comm-more-sec comm-all"><summary>All notes on ${esc(p.book)} ${p.ch}</summary><div class="comm-all-body"></div></details>`);
  if(d.intro) more.push(`<details class="comm-more-sec"><summary>Introduction to ${esc(p.book)}</summary><div class="comm-text">${d.intro}</div></details>`);
  body.innerHTML=picker+`<div class="lbl">${esc(S.name)}</div>`+parts.join("")+more.join("")+`<div class="orig-credit">${S.credit}</div>`;
  bindPick();
  // "All notes" is drawn when opened — a chapter of Matthew Henry can run to tens of thousands of words.
  const all=body.querySelector(".comm-all");
  if(all) all.addEventListener("toggle",()=>{ const box=all.querySelector(".comm-all-body"); if(all.open&&!box.innerHTML){ box.innerHTML=notes.map(r=>commBlock(vlabel(r[0],r[1]),r[2])).join(""); bindComm(box); } });
  bindComm(body);
}
function bindComm(root){
  root.querySelectorAll("a.cref").forEach(a=>{ a.href=verseLink(a.dataset.r); a.onclick=e=>{ e.preventDefault(); gotoVerse(a.dataset.r); }; });
  root.querySelectorAll(".comm-more").forEach(b=>b.onclick=()=>{ b.previousElementSibling.classList.remove("clamp"); b.remove(); });
}

